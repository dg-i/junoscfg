"""Generate the CLI command and option reference from Click declarations."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

import click

from junoscfg.cli import main

if TYPE_CHECKING:
    from collections.abc import Iterator

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = REPO_ROOT / "docs/guide/cli-reference.md"


def _escape(value: object) -> str:
    """Make a value safe and single-line inside a Markdown table cell."""
    return " ".join(str(value).split()).replace("|", "\\|")


def _description(command: click.Command) -> str:
    """Return the first help paragraph without terminal wrapping directives."""
    help_text = command.help or ""
    paragraph = help_text.split("\n\n", 1)[0].replace("\b", "")
    return " ".join(paragraph.split())


def _default(option: click.Option, ctx: click.Context) -> str:
    """Render an option default without calling dynamic factories."""
    value = option.get_default(ctx, call=False)
    if (
        value is None
        or value is False
        or value == ()
        or (type(value).__name__ == "Sentinel" and getattr(value, "name", None) == "UNSET")
    ):
        return "—"
    if callable(value):
        return "dynamic"
    if isinstance(value, (tuple, list)):
        return f"`{_escape(', '.join(str(item) for item in value))}`"
    return f"`{_escape(value)}`"


def _metavar(param: click.Parameter, ctx: click.Context) -> str:
    """Return Click's displayed value placeholder for a parameter."""
    if isinstance(param, click.Option) and param.is_flag:
        return "flag"
    return f"`{_escape(param.make_metavar(ctx))}`"


def _contexts(
    command: click.Command,
    path: tuple[str, ...] = ("junoscfg",),
    parent: click.Context | None = None,
) -> Iterator[tuple[tuple[str, ...], click.Command, click.Context]]:
    """Walk the command tree in declaration order with correctly nested contexts."""
    ctx = command.make_context(path[-1], [], parent=parent, resilient_parsing=True)
    yield path, command, ctx
    if isinstance(command, click.Group):
        for name, child in command.commands.items():
            yield from _contexts(child, (*path, name), ctx)


def _option_rows(command: click.Command, ctx: click.Context) -> list[str]:
    """Render declared options plus Click's contextual help option."""
    options = [param for param in command.params if isinstance(param, click.Option)]
    if ctx.help_option_names:
        options.append(
            click.Option(
                list(ctx.help_option_names),
                is_flag=True,
                expose_value=False,
                is_eager=True,
                help="Show this message and exit.",
            )
        )

    rows: list[str] = []
    for option in options:
        spellings_in_order = sorted(
            (*option.opts, *option.secondary_opts),
            key=lambda value: (value.startswith("--"), value),
        )
        spellings = "<br>".join(f"`{_escape(spelling)}`" for spelling in spellings_in_order)
        required = "yes" if option.required else "no"
        description = _escape(option.help or "")
        rows.append(
            f"| {spellings} | {_metavar(option, ctx)} | {_default(option, ctx)} "
            f"| {required} | {description} |"
        )
    return rows


def _argument_rows(command: click.Command, ctx: click.Context) -> list[str]:
    """Render positional arguments declared for one command."""
    rows: list[str] = []
    for argument in (param for param in command.params if isinstance(param, click.Argument)):
        required = "yes" if argument.required else "no"
        rows.append(
            f"| `{_escape(argument.human_readable_name)}` | {_metavar(argument, ctx)} "
            f"| {required} |"
        )
    return rows


def render_cli_reference() -> str:
    """Return the complete deterministic Markdown reference."""
    lines = [
        "# CLI Command and Option Reference",
        "",
        "<!-- Generated by `python tools/generate_cli_reference.py`; do not edit by hand. -->",
        "",
        "This page is generated from the Click command tree. For explanations and worked",
        "examples, see the [CLI guide](cli.md).",
        "",
    ]

    for path, command, ctx in _contexts(main):
        command_path = " ".join(path)
        usage = command.get_usage(ctx).removeprefix("Usage: ").strip()
        lines.extend(
            [f"## `{command_path}`", "", _description(command), "", "```text", usage, "```", ""]
        )

        option_rows = _option_rows(command, ctx)
        if option_rows:
            lines.extend(
                [
                    f"### Options: `{command_path}`",
                    "",
                    "| Option | Value | Default | Required | Description |",
                    "|---|---|---|---|---|",
                    *option_rows,
                    "",
                ]
            )

        argument_rows = _argument_rows(command, ctx)
        if argument_rows:
            lines.extend(
                [
                    f"### Arguments: `{command_path}`",
                    "",
                    "| Argument | Value | Required |",
                    "|---|---|---|",
                    *argument_rows,
                    "",
                ]
            )

    return "\n".join(lines).rstrip() + "\n"


def main_cli() -> None:
    """Write the generated reference to its committed location."""
    OUTPUT_PATH.write_text(render_cli_reference())


if __name__ == "__main__":
    main_cli()
